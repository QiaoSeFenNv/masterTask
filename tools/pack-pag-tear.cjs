/** Pack only tear.pag; an AE export can replace it without rebuilding reveal.pag. */
const fs=require('node:fs/promises'),path=require('node:path'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..');
function validate(spec,data) {
  if(data.length<11 || data.subarray(0,3).toString()!=='PAG' || data[3]<1 || data[3]>2 || data[8]!==85 || data.readUInt32LE(4)!==data.length-9)
    throw new Error('Expected an unencrypted PAG file with an uncompressed tag body.');
  if(spec.width!==375 || spec.height!==500 || spec.frameRate!==60 || spec.durationMs!==require("../game/js/tear-flight.js").DURATION_MS || spec.transparent!==true)
    throw new Error('PAG tear must be transparent, 375x500, 60fps and 2200ms.');
  const names=['strip-flat','strip-curl','strip-fold','fiber','packet-mouth','packet-body','card-back','series-glow'];
  if(!Array.isArray(spec.textures) || spec.textures.length!==names.length || spec.textures.some((texture,index)=>texture.name!==names[index] || texture.imageIndex!==index || texture.width<=0 || texture.height<=0))
    throw new Error('PAG tear texture indices and layer names do not match the contract.');
}
async function packTearTemplate(spec,data,root=ROOT) {
  validate(spec,data);
  const packaged={encoding:'base64',byteLength:data.length,sha256:crypto.createHash('sha256').update(data).digest('hex'),data:data.toString('base64')};
  await fs.mkdir(path.join(root,'game/data'),{recursive:true});await fs.mkdir(path.join(root,'game/js'),{recursive:true});
  await fs.writeFile(path.join(root,'game/data/tear-pag.js'),'// Generated by tools/pack-pag-tear.cjs; do not edit.\nmodule.exports = '+JSON.stringify(packaged)+';\n');
  await fs.writeFile(path.join(root,'game/js/pag-tear-template.js'),'// Generated by tools/pack-pag-tear.cjs; do not edit.\nmodule.exports = '+JSON.stringify(spec,null,2)+';\n');
  return {bytes:data.length,sha256:packaged.sha256};
}
async function main() {
  const spec=JSON.parse(await fs.readFile(path.join(ROOT,'tools/pag/tear-template.json'),'utf8'));
  const result=await packTearTemplate(spec,await fs.readFile(path.join(ROOT,'game/assets/pag/tear.pag')));
  console.log('Packaged tear.pag ('+result.bytes+' bytes): '+result.sha256);
}
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={packTearTemplate,validate};
