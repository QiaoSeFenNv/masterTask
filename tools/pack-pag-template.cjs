/** Package an existing .pag (including an AE export) for WeChat mini-game loading. */
const fs=require('node:fs/promises');
const path=require('node:path');
const crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..');
async function packTemplate(spec,data) {
  if(data.length<11 || data.subarray(0,3).toString()!=='PAG' || data[3]<1 || data[3]>2 || data[8]!==85)
    throw new Error('Expected an unencrypted PAG file with an uncompressed tag body.');
  if(data.readUInt32LE(4)!==data.length-9)throw new Error('PAG body length does not match the file.');
  if(!spec.card || spec.card.layerName!=='card' || spec.card.imageIndex!==0)
    throw new Error('The editable card must be layer card at image index 0.');
  const packaged={encoding:'base64',byteLength:data.length,sha256:crypto.createHash('sha256').update(data).digest('hex'),data:data.toString('base64')};
  await fs.mkdir(path.join(ROOT,'game/data'),{recursive:true});
  await fs.writeFile(path.join(ROOT,'game/data/reveal-pag.js'),'// Generated PAG binary; packaged as JS for WeChat mini-game file access.\nmodule.exports = '+JSON.stringify(packaged)+';\n');
  await fs.writeFile(path.join(ROOT,'game/js/pag-template.js'),'// Generated by tools/pack-pag-template.cjs.\nmodule.exports = '+JSON.stringify(spec,null,2)+';\n');
  return {bytes:data.length,sha256:packaged.sha256};
}
async function main() {
  const spec=JSON.parse(await fs.readFile(path.join(ROOT,'tools/pag/reveal-template.json'),'utf8'));
  const result=await packTemplate(spec,await fs.readFile(path.join(ROOT,'game/assets/pag/reveal.pag')));
  console.log('Packaged PAG template ('+result.bytes+' bytes): '+result.sha256);
}
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={packTemplate};
