/**
 * 同步 shared/roles.json -> game/data/roles.js(小游戏用)与
 * miniprogram-mp/data/roles.js(旧小程序版,已归档在 miniprogram-mp/)。
 *
 * 小游戏运行时不支持 require 任意路径的 JSON,所以生成一份 CommonJS 模块。
 * 用法:node tools/sync-roles.cjs
 */
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "shared", "roles.json");
const DEST_GAME = path.join(ROOT, "game", "data", "roles.js");

const source = JSON.parse(fs.readFileSync(SRC, "utf8"));

const ids = new Set();
const taskIds = new Set();
for (const role of source.roles) {
  if (ids.has(role.id)) throw new Error("重复的角色 id: " + role.id);
  ids.add(role.id);
  if (!Array.isArray(role.tasks) || role.tasks.length === 0) {
    throw new Error("角色 " + role.id + " 没有任务");
  }
  for (const task of role.tasks) {
    if (taskIds.has(task.id)) throw new Error("重复的任务 id: " + task.id);
    taskIds.add(task.id);
    if (!task.text) throw new Error("任务 " + task.id + " 缺少文案");
  }
}

const body =
  "// generated by tools/sync-roles.cjs -- do not edit\n" +
  "module.exports = " +
  JSON.stringify({ version: source.version, roles: source.roles }) +
  ";\n";

fs.mkdirSync(path.dirname(DEST_GAME), { recursive: true });
fs.writeFileSync(DEST_GAME, body, "utf8");

console.log(
  "OK " +
    source.roles.length +
    " roles / " +
    taskIds.size +
    " tasks -> game/data/roles.js",
);
